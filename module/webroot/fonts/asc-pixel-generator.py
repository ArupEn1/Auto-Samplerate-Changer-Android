U=100  # units per pixel
cmap={}
names=['.notdef']; glyphs={}
def draw(rows,shift=0):
    pen=TTGlyphPen(None)
    for r,row in enumerate(rows):
        for c,ch in enumerate(row):
            if ch=='#':
                x0=(c-shift)*U; x1=x0+U; y1=(7-r)*U+ 200; y0=y1-U   # baseline: 2 px descender room
                y1-=200; y0-=200
                pen.moveTo((x0,y0)); pen.lineTo((x0,y1)); pen.lineTo((x1,y1)); pen.lineTo((x1,y0)); pen.closePath()
    return pen.glyph()
glyphs['.notdef']=draw(["#####","#...#","#...#","#...#","#...#","#...#","#####"])
adv={'.notdef':6*U}
def gname(ch): return 'uni%04X'%ord(ch)
for ch,rows in G.items():
    n=gname(ch); names.append(n); cmap[ord(ch)]=n
    if ch in "I!.,:;'|`":
        cols=[c for r in rows for c,x in enumerate(r) if x=='#']
        lo,hi=min(cols),max(cols); glyphs[n]=draw(rows,lo); adv[n]=(hi-lo+2)*U
    else:
        glyphs[n]=draw(rows); adv[n]=6*U
for ch in "abcdefghijklmnopqrstuvwxyz":
    cmap[ord(ch)]=gname(ch.upper())
